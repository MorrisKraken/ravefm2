static void rfm_char(uint32_t x, uint32_t y, uint32_t s, char ch, uint16_t col)
{
    uint32_t r, c, i = (uint8_t)ch;
    if (i >= 'a' && i <= 'z')
        i -= 32u;
    i = i >= 32u && i < 91u ? i - 32u : 0u;
    for (r = 0; r < 7u; r++)
        for (c = 0; c < 5u; c++)
            if (RFM_FONT[i][r] & (0x10u >> c))
                lcd_fill(x + c * s, y + r * s, s, s, col);
}
/* s centred (center) or from x, its top at y */
static void draw_text_box(uint32_t x, uint32_t y, uint32_t w, const rfm_face_t *f, const char *s, uint16_t col, int center)
{
    uint32_t n = 0, adv = 6u * f->scale;
    while (s[n])
        n++;
    if (center && n * adv < w)
        x += (w - n * adv + f->scale) / 2u;
    for (; *s && x + 5u * f->scale <= 240u; s++, x += adv)
        rfm_char(x, y, f->scale, *s, col);
}
