"""RAVE FM 2's screen palettes, in JIANT's layout (gfx.c ux: bg surf text theme accent mid dim line sel tint rec raise,
then KNOB 1..4's colours). Each palette black and three colours that go together (A the values and cards, B the active thing,
C the text); the drawings drawn in the same three (UI_ART_INK).
   gen_rfm_palettes.py OUT.h"""
import sys

RED, YELLOW, GREEN, VIOLET, WHITE = (255, 50, 60), (255, 214, 0), (40, 240, 90), (150, 100, 255), (240, 238, 246)
PINK = (240, 90, 220)
# (the boot logo's violet, measured on its lit chrome: H 268, S 0.63, V 0.94) and its lilac
LOGO_VIOLET, LILAC = (160, 88, 240), (206, 172, 255)
# name, A (the values, the tabs, the cards; the drawings' halo), B (the one active thing; the drawings' line),
# C (the text; where the drawings' two inks cross)
COLOURS = [("NEON", RED, VIOLET, PINK), ("ACIDE", YELLOW, GREEN, WHITE), ("TOXIC", GREEN, VIOLET, WHITE),
           ("FEU", RED, YELLOW, WHITE), ("SPECTRE", WHITE, VIOLET, RED),
           ("VIOLET", LOGO_VIOLET, LILAC, WHITE)]


def c(r, g, b): return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
def sh(col, k): return tuple(int(v * k) for v in col)
def tint(col, k): return tuple(int(v + (255 - v) * k) for v in col)


def palette(A, B, C):
    """the twelve, the four knobs (all A: the cards alike), the drawings' three inks"""
    text = C if C == WHITE else tint(C, 0.35)
    twelve = [(0, 0, 0), sh(A, 0.09), text, A, B, sh(text, 0.6), sh(A, 0.36), sh(A, 0.2), sh(A, 0.8), sh(A, 0.14), B,
              sh(A, 0.12)]
    return twelve, [A] * 4, (A, B, C)


def main(out):
    L = ["/* generated by tools/gen_rfm_palettes.py: RAVE FM 2's palettes (black and one colour), in the order of gfx.c's ux */",
         "#pragma once", "#include <stdint.h>", "", "static const ui_pal_t UI_PALETTES[] = {"]
    for n, *col in COLOURS:
        t, k, i = palette(*col)
        L.append('    {"%s", {%s}},' % (n, ", ".join("0x%04x" % c(*x) for x in t)))
    L += ["};", "static const uint16_t UI_KNOBS[][4] = {"]
    for n, *col in COLOURS:
        t, k, i = palette(*col)
        L.append("    {%s},   /* %s */" % (", ".join("0x%04x" % c(*x) for x in k), n))
    L += ["};", "static const uint16_t UI_ART_INK[][3] = {   /* the drawings' inks: the halo, the line, where they cross */"]
    for n, *col in COLOURS:
        t, k, i = palette(*col)
        L.append("    {%s},   /* %s */" % (", ".join("0x%04x" % c(*x) for x in i), n))
    L += ["};", "#define UI_NPALETTES %du" % len(COLOURS), "#define UI_JIANT_INDEX 0u", "#define UI_KEY_PCT 78",
          "#define UI_PAL_TAG 64u", "static const uint8_t UI_PAL_STORED[] = {%s};" % ", ".join(str(i) for i in range(len(COLOURS))),
          "static const uint8_t UI_PAL_READ[] = {%s};" % ", ".join(str(i) for i in range(len(COLOURS))),
          "static const uint8_t UI_PALETTE_MIGRATE[20] = {0};"]
    open(out, "w").write("\n".join(L) + "\n")
    print("palettes:", len(COLOURS))


if __name__ == "__main__":
    main(sys.argv[1])
