"""RAVE FM 2's smooth fonts: glyphs rasterised here from the TTFs in assets/fonts (OFL), 4 bits of coverage a pixel,
each trimmed to its ink box.
  M: Russo One 13 px (names)   L: Anton 24 px (the knobs' values, the tempo)   XL: Anton 38 px, digits (big numbers)
  T: Black Ops One 16 px (stencil: titles)
  gen_aafont.py OUT.h"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONTS = HERE.parent / "assets" / "fonts"
ASCII = "".join(chr(c) for c in range(32, 127))
FACES = [("M", "RussoOne-Regular.ttf", 13, ASCII), ("L", "Anton-Regular.ttf", 24, ASCII),
         ("XL", "Anton-Regular.ttf", 38, " 0123456789.+-%:/BPM"), ("T", "BlackOpsOne-Regular.ttf", 16, ASCII)]


def face(name, ttf, size, chars):
    f = ImageFont.truetype(str(FONTS / ttf), size)
    asc, desc = f.getmetrics()
    recs, data = [], bytearray()
    for ch in chars:
        adv = f.getlength(ch)
        im = Image.new("L", (size * 2, asc + desc + 4), 0)
        ImageDraw.Draw(im).text((4, 0), ch, font=f, fill=255)
        bb = im.getbbox()
        if not bb:
            recs.append((len(data), round(adv), 0, 0, 0, 0))
            continue
        x0, y0, x1, y1 = bb
        g = im.crop(bb)
        w, h = g.size
        px = list(g.get_flattened_data()) if hasattr(g, "get_flattened_data") else list(g.getdata())
        off = len(data)
        for y in range(h):
            row = [min(15, (v + 8) >> 4) for v in px[y * w:(y + 1) * w]]
            if w % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] | row[i + 1] << 4)
        recs.append((off, round(adv), x0 - 4, y0, w, h))
    return dict(name=name, h=asc + desc, asc=asc, chars=chars, recs=recs, data=data)


def main(out):
    L = ["/* generated by tools/gen_aafont.py: RAVE FM 2's smooth fonts (Anton, Russo One, Black Ops One; OFL: assets/fonts) */",
         "typedef struct { uint16_t off; uint8_t adv; int8_t bx; uint8_t by, bw, bh; } rfm_glyph_t;",
         "typedef struct { uint8_t h, asc, n; const char *map; const rfm_glyph_t *g; const uint8_t *data; } rfm_aafont_t;"]
    total = 0
    for name, ttf, size, chars in FACES:
        F = face(name, ttf, size, chars)
        n = F["name"]
        L.append(f"static const uint8_t AA_{n}_DATA[{len(F['data']) or 1}] = {{")
        d = F["data"]
        for k in range(0, len(d), 32):
            L.append("    " + ", ".join(str(b) for b in d[k:k + 32]) + ",")
        L.append("};")
        L.append(f"static const rfm_glyph_t AA_{n}_G[{len(F['recs'])}] = {{")
        for r in F["recs"]:
            L.append("    {%d, %d, %d, %d, %d, %d}," % r)
        L.append("};")
        cmap = F["chars"].replace("\\", "\\\\").replace('"', '\\"')
        L.append(f'static const rfm_aafont_t AA_{n} = {{{F["h"]}, {F["asc"]}, {len(chars)}, "{cmap}", AA_{n}_G, AA_{n}_DATA}};')
        total += len(d) + len(F["recs"]) * 7
        print(f"font {n}: {len(chars)} glyphs, {len(d)} B")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"fonts: {total} B")


if __name__ == "__main__":
    main(sys.argv[1])
