"""RAVE FM 2's boot screen: the original bat and its "RAVE FM", in their violet, out of the original start screen
(assets/ravefm_boot_ref.png: rows 30..181 only, nothing else of it), as 16 colours, run-length coded:
each byte (run - 1) << 4 | colour, run 1..16.
  gen_boot.py OUT.h"""
import sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
TOP, BOT = 28, 140          # the bat only (its old name under it: redrawn, tools/gen_chrome_logo.py)
LOGO_H = 66


def pack(im, name, lines):
    """16 colours (index 0 the darkest), run-length; its C arrays appended to lines"""
    w, h = im.size
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = (q.getpalette()[:48] + [0] * 48)[:48]
    cols = [tuple(pal[i * 3:i * 3 + 3]) for i in range(16)]
    order = sorted(range(16), key=lambda i: sum(cols[i]))
    remap = {o: n for n, o in enumerate(order)}
    cols = [cols[o] for o in order]
    data = [remap[v] for v in q.getdata()]
    rle, i = bytearray(), 0
    while i < len(data):
        c, n = data[i], 1
        while n < 16 and i + n < len(data) and data[i + n] == c:
            n += 1
        rle.append((n - 1) << 4 | c)
        i += n
    lines += [f"#define {name}_W {w}", f"#define {name}_H {h}",
              f"static const uint8_t {name}_RGB[16][3] = {{" + ", ".join("{%d, %d, %d}" % c for c in cols) + "};",
              f"static const uint8_t {name}_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        lines.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    lines.append("};")
    return len(rle)


def main(out):
    im = Image.open(HERE.parent / "assets" / "ravefm_boot_ref.png").convert("RGB").crop((0, TOP, 240, BOT))
    w, h = im.size
    px = im.load()
    for y in range(h):                       # the ground: black
        for x in range(w):
            r, g, b = px[x, y]
            if max(r, g, b) < 14:
                px[x, y] = (0, 0, 0)
    sys.path.insert(0, str(HERE))
    import gen_chrome_logo
    rgb, al = gen_chrome_logo.logo(LOGO_H)
    logo = Image.new("RGB", rgb.size, (0, 0, 0))
    logo.paste(rgb, (0, 0), al)
    lines = ["/* generated by tools/gen_boot.py: the original bat (assets/ravefm_boot_ref.png) and RAVE FM in chrome"
             " (tools/gen_chrome_logo.py) */"]
    n1 = pack(im, "RFM_BOOT", lines)
    n2 = pack(logo, "RFM_LOGO", lines)
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"boot: bat {w}x{h} {n1} B, logo {logo.size[0]}x{logo.size[1]} {n2} B")


if __name__ == "__main__":
    main(sys.argv[1])
