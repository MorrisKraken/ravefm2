"""RAVE FM 2's instrument drawings: Maxime's line art (assets/maxime/planche1.png, planche2.png), each drawing cut out,
its two inks split (the warm lines and the cool ones), brought down to the screen, kept as 2 bits of each ink a pixel
(0..3: how much of the ink), run-length coded. On the FM-1 each ink is the palette's (UI_ART), so they follow it.
  gen_art.py preview DIR       PNG previews (in each palette)
  gen_art.py header OUT.h      the C data"""
import sys
from pathlib import Path
import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent.parent
BOX_W, BOX_H = 200, 128          # the most a drawing takes on the EDIT page
CELL_W, CELL_H = 384, 512
# key, sheet, cell (col, row), what it is
ART = [
    ("KICK", 2, (1, 1), "the horned skull, its spikes"),
    ("BREAK", 1, (3, 1), "the man in chains, screaming"),
    ("BASS", 1, (2, 0), "the ram-horned demon"),
    ("ACID", 2, (2, 0), "the cobra"),
    ("LEAD", 1, (1, 0), "the jester"),
    ("STAB", 2, (3, 0), "the cyborg"),
    ("HOOVER", 1, (0, 1), "the alien"),
    ("PAD", 1, (3, 0), "the pharaoh"),
    ("PLUCK", 1, (2, 1), "the spider"),
    ("FX", 1, (1, 1), "the gas mask"),
    ("SAMPLE", 1, (0, 0), "the two skeletons"),
]
# the inks per palette (in tools/gen_rfm_palettes.py's order): the warm one (the sheets' red), the cool one (their blue)
INKS = {"BLOOD": ((255, 64, 72), (122, 104, 255)), "TERROR": ((240, 36, 36), (220, 250, 0)),
        "FIRE": ((255, 214, 60), (255, 96, 24)), "STEEL": ((236, 44, 44), (196, 200, 212))}


def cut(key, sheet, cell):
    im = np.asarray(Image.open(HERE / "assets" / "maxime" / f"planche{sheet}.png").convert("RGB"), np.float32)
    c, r = cell
    a = im[r * CELL_H:(r + 1) * CELL_H, c * CELL_W:(c + 1) * CELL_W]
    R, G, B = a[..., 0], a[..., 1], a[..., 2]
    lum = np.maximum(np.maximum(R, G), B) / 255
    warm = np.clip((R - B) / 120 + 0.15, 0, 1) * lum            # the red lines
    cool = np.clip((B - R) / 120 + 0.15, 0, 1) * lum            # the blue lines
    mag = np.clip(1 - np.abs(R - B) / 120, 0, 1) * lum          # (magenta: a bit of both)
    warm, cool = np.maximum(warm, mag * 0.6), np.maximum(cool, mag * 0.6)
    ink = np.maximum(warm, cool)
    from scipy import ndimage as nd                             # (bits of the neighbouring drawings: away)
    lab, n = nd.label(nd.binary_dilation(ink > 0.25, iterations=6))
    sizes = nd.sum(ink > 0.25, lab, range(1, n + 1))
    keep = np.isin(lab, 1 + np.where(sizes > sizes.max() * 0.04)[0])
    warm, cool, ink = warm * keep, cool * keep, ink * keep
    ys, xs = np.where(ink > 0.25)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    warm, cool = warm[y0:y1, x0:x1], cool[y0:y1, x0:x1]
    h, w = warm.shape
    s = min(BOX_W / w, BOX_H / h)
    ow, oh = max(1, round(w * s)), max(1, round(h * s))
    def down(ch):                                               # the lines thin out when brought down: area, then lift
        im2 = Image.fromarray((ch * 255).astype(np.uint8)).resize((ow, oh), Image.BOX)
        v = np.asarray(im2, np.float32) / 255
        v = np.clip(v * 2.6, 0, 1) ** 0.75
        return np.clip(np.round(v * 3), 0, 3).astype(np.uint8)
    return down(warm), down(cool)


def rle(lw, lc):
    flat = list((lw.astype(np.uint8) << 2 | lc).flatten())
    out, i = [], 0
    while i < len(flat):
        v, n = flat[i], 1
        while i + n < len(flat) and flat[i + n] == v and n < 16:
            n += 1
        out.append((n - 1) << 4 | v)
        i += n
    return out


def show(lw, lc, inks, bg=(0, 0, 0)):
    a, b = np.array(inks[0], np.float32), np.array(inks[1], np.float32)
    rgb = np.array(bg, np.float32) + (lw[..., None] / 3) * a + (lc[..., None] / 3) * b
    return Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8))


def rgb565(c):
    return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return
    arts = [(k, cut(k, s, c)) for k, s, c, _ in ART]
    if sys.argv[1] == "preview":
        d = Path(sys.argv[2]); d.mkdir(parents=True, exist_ok=True)
        for pname, inks in INKS.items():
            sheet = Image.new("RGB", (6 * (BOX_W + 10) + 10, 2 * (BOX_H + 10) + 10), (0, 0, 0))
            for i, (k, (lw, lc)) in enumerate(arts):
                im = show(lw, lc, inks)
                x, y = 10 + (i % 6) * (BOX_W + 10), 10 + (i // 6) * (BOX_H + 10)
                sheet.paste(im, (x + (BOX_W - im.width) // 2, y + (BOX_H - im.height) // 2))
            sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(d / f"art_{pname}.png")
        return
    if sys.argv[1] == "header":
        L = [f"/* generated by tools/gen_art.py: Maxime's line art for the instruments (assets/maxime), 2 inks x 2 bits a"
             " pixel (warm << 2 | cool), run-length: byte = (run - 1) << 4 | value */", f"#define RFM_NART {len(arts)}"]
        total = 0
        for i, (k, (lw, lc)) in enumerate(arts):
            L.append(f"#define RFM_ART_{k} {i}")
        for i, (k, (lw, lc)) in enumerate(arts):
            r = rle(lw, lc)
            total += len(r)
            L.append(f"static const uint8_t RFM_ART_RLE_{i}[{len(r)}] = {{")
            for j in range(0, len(r), 32):
                L.append("    " + ", ".join(str(v) for v in r[j:j + 32]) + ",")
            L.append("};")
        L.append("static const uint8_t *const RFM_ART_RLE[RFM_NART] = {" + ", ".join(f"RFM_ART_RLE_{i}" for i in range(len(arts))) + "};")
        L.append("static const uint8_t RFM_ART_WH[RFM_NART][2] = {" + ", ".join(f"{{{lw.shape[1]}, {lw.shape[0]}}}" for k, (lw, lc) in arts) + "};")
        L.append("static const uint16_t RFM_ART_INK[][2] = {" + ", ".join(f"{{0x{rgb565(a):04X}, 0x{rgb565(b):04X}}}" for a, b in INKS.values()) + "};   /* per palette: warm, cool */")
        L.append(f"/* {total} bytes */")
        Path(sys.argv[2]).write_text("\n".join(L) + "\n")
        print(total, "bytes")


if __name__ == "__main__":
    main()
