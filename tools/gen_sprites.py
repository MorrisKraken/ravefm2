ORDER = ["KICK", "KIT", "909", "BASS", "LEAD", "STAB", "HOOVER", "SAMPLE"]   # = tb_ui.h TB_ICON_*


def bits(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), art
    out = []
    for r in rows:
        v = 0
        for i, ch in enumerate(r):
            if ch == "#":
                v |= 1 << (15 - i)
        out += [v >> 8, v & 255]
    return out


def main(out):
    lines = ["/* generated by tools/gen_sprites.py: the tracks' icons, 16 x 16, at rest and hit (TB_ICON_* order) */",
             "static const uint8_t RFM_ICON[8][2][32] = {"]
    for n in ORDER:
        a, b = S[n]
        lines.append(f"    {{{{{', '.join(map(str, bits(a)))}}},   /* {n} */")
        lines.append(f"     {{{', '.join(map(str, bits(b)))}}}}},")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print("sprites: 8 icons")


if __name__ == "__main__":
    main(sys.argv[1])
