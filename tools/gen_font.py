def main(out):
    codes = list(range(32, 130))
    glyphs, widths = [], []
    for c in codes:
        rows = G[chr(c)]
        w = max([len(r) for r in rows if r] + [1 if c != 32 else 3])
        bits = []
        for r in rows:
            v = 0
            for i, ch in enumerate(r):
                if ch == "#":
                    v |= 1 << (4 - i)
            bits.append(v)
        glyphs.append(bits)
        widths.append(w)
    lines = ["/* generated by tools/gen_font.py: RAVE FM 2's pixel font, 5 x 9 (7 over the baseline), codes 32..129 */",
             "#define RFM_FONT_FIRST 32", f"#define RFM_FONT_N {len(codes)}",
             "static const uint8_t RFM_FONT_W[RFM_FONT_N] = {" + ", ".join(map(str, widths)) + "};",
             "static const uint8_t RFM_FONT[RFM_FONT_N][9] = {"]
    for c, b in zip(codes, glyphs):
        lines.append("    {" + ", ".join(f"0x{v:02X}" for v in b) + "},   /* " + (repr(chr(c)) if c < 127 else str(c)) + " */")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"font: {len(codes)} glyphs")


if __name__ == "__main__":
    main(sys.argv[1])
